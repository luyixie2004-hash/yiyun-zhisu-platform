let isLoading = false // 防止重复点击
let isGoingBack = false // 防止返回按钮重复点击

async function loadMapData(adcode, name, level) {
  if (isLoading) return
  isLoading = true
  try {
    const res = await fetch(`/map/${adcode}_full.json`)
    if (!res.ok) throw new Error(`地图文件不存在: ${adcode}`)
    const geoJson = await res.json()
    echarts.registerMap(name, geoJson)
    currentGeoJson = geoJson
    mapLevel.value = level
    currentAreaName.value = name
    
    // 生成展示数据
    let data;
    if (level === 1) {
      data = geoJson.features.map(f => {
        const shortName = provinces.find(p => f.properties.name.includes(p)) || f.properties.name;
        const exist = mapData.find(m => m.name === shortName);
        return {
          name: f.properties.name,
          value: exist ? exist.value : Math.floor(Math.random() * 200) + 10,
          shortName: shortName
        };
      });
    } else {
      data = geoJson.features.map(f => ({
        name: f.properties.name,
        value: Math.floor(Math.random() * 200) + 10,
        shortName: f.properties.name
      }));
    }

    mapChart.setOption({
      series: [{ 
        type: 'map',
        map: name, 
        data, 
        zoom: 1, 
        center: null,
        roam: true,
        scaleLimit: { min: 0.8, max: 5 },
        label: { show: true, color: '#111', fontSize: 10, fontWeight: 500 },
        itemStyle: { borderColor: 'rgba(255,255,255,0.5)', borderWidth: 1 },
        emphasis: { itemStyle: { areaColor: '#fec44f', shadowBlur: 10 }, label: { color: '#000', fontWeight: 'bold' } }
      }]
    })
    
    updateBarChart(data);
  } catch (e) {
    message.warning(`获取 ${name} 地图数据失败，可能已是最小层级或网络错误。`)
  } finally {
    isLoading = false
  }
}

async function handleMapClick(params) {
  const feature = currentGeoJson?.features.find(f => f.properties.name === params.name)
  if (!feature) return

  if (mapChart) {
    mapChart.dispatchAction({ type: 'downplay' })
  }

  const adcode = feature.properties.adcode

  if (mapLevel.value === 1) { // 全国 -> 省
    mapHistory.push({ level: 1, name: '全国', geoJson: currentGeoJson })
    await loadMapData(adcode, params.name, 2)
    fetchProjects()
  }
  else if (mapLevel.value === 2) { // 省 -> 市
    mapHistory.push({ level: 2, name: currentAreaName.value, geoJson: currentGeoJson })
    await loadMapData(adcode, params.name, 3)
    fetchProjects()
  }
  else if (mapLevel.value === 3) { // 市 -> 区
  }
}

