function showTooltip(proj, event) {
  tooltipContent.value = proj
  
  // 获取tooltip的尺寸（根据CSS样式）
  const tooltipWidth = 320  // min-width: 280px, max-width: 360px
  const tooltipHeight = 120 // 估算高度
  
  let x = event.clientX
  let y = event.clientY
  let direction = 'left' // 默认显示在左侧
  
  // 检测左侧空间
  const leftSpace = x
  
  // 如果左侧空间不足，显示在右侧
  if (leftSpace < tooltipWidth + 20) {
    direction = 'right'
    x = x + 10
  } else {
    // 显示在左侧
    x = x - tooltipWidth - 10
  }
  
  // 右边边界检测（当显示在右侧时）
  if (direction === 'right' && x + tooltipWidth > window.innerWidth) {
    x = window.innerWidth - tooltipWidth - 10
    // 如果右侧也没空间，尝试显示在顶部
    if (x < 10) {
      x = event.clientX
      direction = 'top'
    }
  }
  
  // 左边边界检测
  if (x < 10) {
    x = 10
  }
  
  // 垂直居中
  if (y - tooltipHeight / 2 < 10) {
    y = 10 + tooltipHeight / 2
  } else if (y + tooltipHeight / 2 > window.innerHeight) {
    y = window.innerHeight - tooltipHeight / 2 - 10
  }
  
  tooltipPosition.value = { x, y, direction }
  tooltipVisible.value = true
}

function hideTooltip() {
  tooltipVisible.value = false
}

function fetchProjects() {
  const res = getProvinceProjects(currentAreaName.value, currentPage.value, pageSize)
  drawerProjects.value = res.items
  totalProjects.value = res.total
  panelPage.value = 1
}

const totalPanelPages = computed(() => {
  return Math.ceil(drawerProjects.value.length / panelPageSize)
})

const paginatedProjects = computed(() => {
  const start = (panelPage.value - 1) * panelPageSize
  const end = start + panelPageSize
  return drawerProjects.value.slice(start, end)
})

function prevPanelPage() {
  if (panelPage.value > 1) {
    panelPage.value--
  }
}

function nextPanelPage() {
  if (panelPage.value < totalPanelPages.value) {
    panelPage.value++
  }
}
