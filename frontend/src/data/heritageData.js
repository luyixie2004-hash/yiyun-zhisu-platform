/** Seeded PRNG (mulberry32) */
function mulberry32(a) {
  return function() {
    var t = a += 0x6D2B79F5
    t = Math.imul(t ^ t >>> 15, t | 1)
    t ^= t + Math.imul(t ^ t >>> 7, t | 61)
    return ((t ^ t >>> 14) >>> 0) / 4294967296
  }
}

/** Simple string hash */
function hashString(str) {
  let h = 0
  for (let i = 0; i < str.length; i++) h = Math.imul(31, h) + str.charCodeAt(i) | 0
  return h
}

/**
 * 获取省份非遗项目（Mock 数据，带缓存一致性）
 * @param {string} provinceName 省份全名（如 "浙江省"）
 * @param {number} page 页码
 * @param {number} pageSize 每页条数
 * @returns {{ total: number, items: Array }}
 */
export function getProvinceProjects(provinceName, page = 1, pageSize = 10) {
  const shortName = provinceName.replace(/(省|市|自治区|维吾尔|壮族|回族|特别行政区)/g, '')
  const realList = realData[shortName] || realData['北京'] // fallback

  const rand = mulberry32(hashString(shortName))
  const total = 50 + Math.floor(rand() * 50) // 50-100 items per province
  const items = []

  for (let i = 0; i < total; i++) {
    if (i < realList.length) {
      const parts = realList[i].split('|')
      items.push({
        id: `${shortName}-${i}`,
        name: parts[0],
        category: parts[1],
        level: i < 2 ? '世界级' : '国家级',
        desc: `${parts[0]}是${shortName}代表性的${parts[1]}非遗项目。它承载了当地深厚的历史文化底蕴和劳动人民的智慧结晶，以其独特的艺术魅力和文化价值闻名，近年来在传承人的努力下得到了良好的保护与发展。`
      })
    } else {
      const cat = categories[Math.floor(rand() * categories.length)]
      const lvl = levels[Math.floor(rand() * levels.length)]
      const mockNames = [
        '传统竹编技艺', '古法酿酒', '地方皮影戏', '民间传说', '特色大鼓', '传统剪纸', '木版年画', '传统武术', '地方戏曲', '面食制作', '民族刺绣', '草编工艺'
      ]
      const name = shortName + mockNames[Math.floor(rand() * mockNames.length)] + `(第${i + 1}项)`
      items.push({
        id: `${shortName}-${i}`,
        name,
        category: cat,
        level: lvl,
        desc: `这是流传在${shortName}地区的${cat}类非遗项目，级别为${lvl}。它在岁月的长河中不断演变，是当地群众生活中不可或缺的文化符号。该项目对研究当地历史人文具有重要价值。`
      })
    }
  }

  const start = (page - 1) * pageSize
  const end = start + pageSize
  return {
    total,
    items: items.slice(start, end)
  }
}
