/**
 * 获取城市对应的区县列表
 * @param {string} cityName 城市名称
 * @returns {string[]} 区县名称数组，未找到则返回空数组
 */
export function getDistricts(cityName) {
  return districtData[cityName] || []
}

/**
 * 获取省份对应的城市列表
 * @param {string} provinceName 省份名称（支持带"省"/"市"后缀和不带的格式）
 * @returns {string[]} 城市名称数组，未找到则返回空数组
 */
export function getCities(provinceName) {
  // 尝试直接匹配
  if (cityData[provinceName]) return cityData[provinceName]
  // 去掉后缀再试
  const shortName = provinceName.replace(/(省|市|自治区|维吾尔|壮族|回族|特别行政区)/g, '')
  if (cityData[shortName]) return cityData[shortName]
  // 模糊匹配
  for (const [key, value] of Object.entries(cityData)) {
    if (key.includes(shortName) || shortName.includes(key)) return value
  }
  return []
}
